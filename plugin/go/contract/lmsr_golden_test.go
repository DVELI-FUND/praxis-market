func TestLegacyLmsrGolden(t *testing.T) {
	for i, g := range legacyLmsrGolden {
		got, pe := ComputeTradeCost(g.qYes, g.qNo, g.bEff, g.shares, g.outcome)
		if pe != nil {
			t.Fatalf("case %d: %v", i, pe)
		}
		if got != g.cost {
			t.Fatalf("case %d (qYes=%d qNo=%d b=%d shares=%d yes=%v): cost %d != golden %d — float64 LMSR differs on this architecture",
				i, g.qYes, g.qNo, g.bEff, g.shares, g.outcome, got, g.cost)
		}
	}
}

