// TestLegacyLmsrFloatBitsGolden documents a KNOWN cross-architecture difference rather than
// failing the suite on arm64 dev machines: with PRAXIS_STRICT_FLOAT=1 a mismatch fails.
func TestLegacyLmsrFloatBitsGolden(t *testing.T) {
	bad := 0
	for _, g := range legacyLmsrBits {
		if math.Float64bits(lmsrCostFloat(g.qYes, g.qNo, g.bEff)) != g.bits {
			bad++
		}
	}
	if bad == 0 {
		return
	}
	msg := fmt.Sprintf("%d/%d float64 LMSR results differ from the amd64 golden bits: the legacy binary LMSR is not bit-identical on this architecture (consensus risk only if validators mix architectures)", bad, len(legacyLmsrBits))
	if os.Getenv("PRAXIS_STRICT_FLOAT") == "1" {
		t.Fatal(msg)
	}
	t.Skip("WARNING: " + msg)
}
